"""Curated exercise registry used by plans, workout generation and the client.

The registry is intentionally code-backed for the MVP: it is versioned, has stable
identifiers and needs no deployment-time seeding.  A database-backed editor can
replace this module later without changing the API contract.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Exercise:
    id: str
    name: str
    primary_muscle: str
    secondary_muscles: tuple[str, ...]
    equipment: str
    difficulty: str
    modality: str = "strength"


def _group(
    primary_muscle: str,
    rows: tuple[tuple[str, str, str, str, tuple[str, ...]], ...],
    modality: str = "strength",
) -> tuple[Exercise, ...]:
    return tuple(
        Exercise(
            id=exercise_id,
            name=name,
            primary_muscle=primary_muscle,
            equipment=equipment,
            difficulty=difficulty,
            secondary_muscles=secondary,
            modality=modality,
        )
        for exercise_id, name, equipment, difficulty, secondary in rows
    )


