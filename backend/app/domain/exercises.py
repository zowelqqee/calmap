EXERCISE_BY_ID = {exercise.id: exercise for exercise in EXERCISES}
MUSCLE_GROUPS = tuple(sorted({exercise.primary_muscle for exercise in EXERCISES}))
EQUIPMENT_TYPES = tuple(sorted({exercise.equipment for exercise in EXERCISES}))

if len(EXERCISE_BY_ID) != len(EXERCISES):  # pragma: no cover - import-time catalogue guard
    raise RuntimeError("Exercise registry contains duplicate identifiers")


def get_exercise(exercise_id: str) -> Exercise:
    """Return an exercise by stable ID; fail early when editing workout templates."""
    return EXERCISE_BY_ID[exercise_id]
