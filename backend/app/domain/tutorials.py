"""Technique tutorials for every exercise in the registry.

Each entry answers the questions a person actually has while standing in the
gym: how to set up, what to do, how to breathe, at what tempo, what usually
goes wrong, what it should feel like, and what to do instead when the movement
is too hard or the equipment is taken.

Exercises come in families — six push-up variants share a spine and a shoulder
blade, five rows share a hinge — so a family carries the shared coaching and
each exercise overrides what is genuinely its own.  Every registry id must
resolve to a complete tutorial; `test_tutorials.py` enforces that.
"""

from __future__ import annotations

from dataclasses import dataclass, replace


@dataclass(frozen=True, slots=True)
class Tutorial:
    """A single exercise explained end to end."""

    setup: str
    steps: tuple[str, ...]
    breathing: str
    tempo: str
    mistakes: tuple[str, ...]
    sensation: str
    swap: str


